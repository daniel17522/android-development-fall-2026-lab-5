PostModel _post(
  String id,
  String author,
  int avatar,
  String photo,
  String description,
  List<String> commentTexts,
) {
  final avatarUrl = 'https://i.pravatar.cc/150?img=$avatar';
  return PostModel(
    id: id,
    authorName: author,
    authorAvatarUrl: avatarUrl,
    imageUrl:
        'https://images.unsplash.com/$photo?auto=format&fit=crop&w=900&q=80',
    description: description,
    likeCount: avatar * 3,
    comments: [
      CommentModel(
        authorName: 'Alex',
        avatarUrl: 'https://i.pravatar.cc/150?img=${avatar + 21}',
        message: commentTexts[0],
      ),
      CommentModel(
        authorName: 'Jamie',
        avatarUrl: 'https://i.pravatar.cc/150?img=${avatar + 41}',
        message: commentTexts[1],
      ),
    ],
  );
}
